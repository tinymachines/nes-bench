#!/usr/bin/env python3
"""The build guide: five sittings, one command each, written out.

  python3 tools/build-guide.py            # write docs/build-guide.md
  python3 tools/build-guide.py --check    # exit 1 if it is not current

Generated from `tools/bringup.py`'s own step table and from
`docs/lab-log.jsonl`, so it is the procedure that actually runs and the
state it is actually in, not a second copy of either. Written to be read
on a phone at the bench: what to wire, one command, what that command
checks, and which photographs to take.
"""
import argparse
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOG = ROOT / "docs" / "lab-log.jsonl"
OUT = ROOT / "docs" / "build-guide.md"

CHECK_SAYS = {
    "scope_idn": "asks the scope who it is over the LAN",
    "serial_open": "opens the UNO's serial port, and names the fix if it cannot",
    "bridge_hello": "sends STATUS and reads the bridge's reply",
    "harness_map": "takes your continuity readings, and refuses fewer than four",
    "port_levels": "takes four meter readings and REFUSES to continue if the supply pin is not about 5 V",
    "scope_port_timing": "captures both lines and measures the latch pulse, the clock pulse, the gap between clocks and the polls per second",
    "scope_qh_pattern": "captures QH and decodes the eight bits against the byte your links make",
    "bridge_set_byte": "sets a byte, reads it back from STATUS, and has you meter two of the register's outputs",
    "bridge_pad_follows": "asks you to hold three buttons and checks each one reaches the bridge's pad byte",
    "bridge_eight_clocks": "listens to the bridge for twenty seconds and prints the clocks-per-poll histogram",
    "bridge_pass_through": "checks the game reacts and the log carries the byte",
    "trigger_reaches_scope": "arms the scope on EXT TRIG and fires the bridge's trigger at a latch",
    "reset_pulse": "records which reset pad is ground and checks the pulse resets the console",
    "power_relay": "refuses unless the contact is on the adapter side, then checks it switches",
}


def load(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "tools" / f"{name}.py")
    m = importlib.util.module_from_spec(spec)
    argv, sys.argv = sys.argv, [sys.argv[0]]
    try:
        spec.loader.exec_module(m)
    finally:
        sys.argv = argv
    return m


def read_log():
    if not LOG.exists():
        return []
    out = []
    for line in LOG.read_text().splitlines():
        line = line.strip()
        if line:
            try:
                e = json.loads(line)
                if not e.get("rehearsal"):
                    out.append(e)
            except json.JSONDecodeError:
                pass
    return out


def render():
    b = load("bringup")
    latest = {}
    for e in read_log():
        latest[e["step"]] = e

    L = []
    L.append("# Build guide: five sittings at the bench")
    L.append("")
    L.append("Generated by `tools/build-guide.py` from the step table in")
    L.append("`tools/bringup.py` and the log in `docs/lab-log.jsonl`. It is the")
    L.append("procedure that actually runs and the state it is actually in, so it")
    L.append("cannot drift from either. Re-run that tool and this updates.")
    L.append("")
    L.append("**One command per sitting.** Each one prints what to do, waits, and")
    L.append("then measures something. It never asks whether a step worked. A step")
    L.append("that fails stops the run and tells you which one to repeat.")
    L.append("")
    L.append("The running record, with every attempt and the photographs, is")
    L.append("[the lab notebook](lab-notebook.md). The working document for")
    L.append("whichever cycle is open, and the place the operator's own")
    L.append("observations are written down, is in")
    L.append("[procedures](procedures/README.md).")
    L.append("")

    # Where things stand, per sitting.
    L.append("## Where it stands")
    L.append("")
    L.append("| sitting | what it is | state |")
    L.append("|---|---|---|")
    for n, title, _d, ids in b.SESSIONS:
        done = [i for i in ids if latest.get(i, {}).get("state") == "pass"]
        failed = [i for i in ids if latest.get(i, {}).get("state") == "fail"]
        if len(done) == len(ids):
            state = "done"
        elif failed:
            state = f"stopped at {failed[0]}"
        elif done:
            state = f"{len(done)} of {len(ids)} steps"
        else:
            state = "not started"
        L.append(f"| {n} | {title} | {state} |")
    L.append("")

    L.append("## Before the first sitting")
    L.append("")
    L.append("Two things bite before anything else, and both are one line.")
    L.append("")
    L.append("**The serial port will refuse to open** until your user is in the")
    L.append("`dialout` group:")
    L.append("")
    L.append("```")
    L.append("sudo usermod -aG dialout $USER")
    L.append("```")
    L.append("")
    L.append("Then log out and back in. A new shell is not enough. Check it took")
    L.append("with `id -nG | grep dialout`.")
    L.append("")
    L.append("**The scope's address** lives in `bench.local.md`, which git ignores.")
    L.append("Nothing else needs it, and nothing else should carry it.")
    L.append("")
    L.append("On the desk, over the five sittings: a meter, two scope probes, the")
    L.append("UNO and a USB cable, the console open with a game in it, two original")
    L.append("pads, the breadboard, a 74HC04, a 74HC165, a 74HC595, three 100 nF")
    L.append("capacitors, a 100 ohm resistor, a BNC lead to the scope's rear EXT")
    L.append("TRIG, the PC817 module, the relay module, and the Pi.")
    L.append("")

    for n, title, desc, ids in b.SESSIONS:
        L.append(f"## Sitting {n}: {title}")
        L.append("")
        L.append(desc)
        L.append("")
        L.append("```")
        L.append(f"python3 tools/bringup.py --session {n}")
        L.append("```")
        L.append("")
        for sid in ids:
            st = b.BY_ID[sid]
            e = latest.get(sid)
            mark = {"pass": "held", "fail": "did not hold", "skip": "skipped"}.get(e["state"], "") if e else ""
            head = f"### {sid}  {st['title']}"
            if mark:
                head += f"  ({mark})"
            L.append(head)
            L.append("")
            if st["replaces"]:
                L.append(f"Answers: {st['replaces']}.")
                L.append("")
            cmds = []
            # None is a flush marker, so a trailing run of commands is
            # emitted. It must not itself look like a command.
            for line in st["do"] + [None]:
                if line is not None and line.startswith("$ "):
                    cmds.append(line[2:])
                    continue
                real = [c for c in cmds if c]
                cmds = []
                if real:
                    L.append("")
                    L.append("```")
                    L.extend(real)
                    L.append("```")
                    L.append("")
                if line is None:
                    continue
                if line.startswith("  "):
                    L.append(f"    - {line.strip()}")
                else:
                    L.append(f"- {line}")
            L.append("")
            L.append(f"Then it {CHECK_SAYS.get(st['check'], 'checks the step')}.")
            L.append("")
            if st["photos"]:
                L.append("Photographs:")
                L.append("")
                for ph in st["photos"]:
                    here = (ROOT / "docs" / "lab" / ph).exists()
                    L.append(f"- `docs/lab/{ph}`" + ("  (pushed)" if here else "  (wanted)"))
                L.append("")
            if e:
                L.append(f"> Last run {e['at'].replace('T', ' ')}: {mark}. {e['summary']}")
                L.append("")

    L.append("## When a sitting is done")
    L.append("")
    L.append("```")
    L.append("python3 tools/lab-notebook.py     # fold the run into the notebook")
    L.append("python3 tools/build-guide.py      # and update this page's state")
    L.append("```")
    L.append("")
    L.append("Photographs go in `docs/lab/` under exactly the name the tool asked")
    L.append("for. Push them and re-run those two: the notebook embeds the ones")
    L.append("that arrived and keeps naming the ones that have not, so nothing")
    L.append("here is ever a broken image and nothing is quietly forgotten.")
    L.append("")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is not current: run python3 tools/build-guide.py")
            return 1
        print(f"{OUT} is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
