#!/usr/bin/env python3
"""The esp-hosted slave image the installed Arduino core expects on the
ESP32-P4 module's onboard ESP32-C6, fetched, checked and written into
firmware/p4-c6-update as C.

  python3 tools/fetch-c6-image.py            # fetch, check, write c6_image.c
  python3 tools/fetch-c6-image.py --check    # say what would be fetched, fetch nothing

NOTHING HERE IS TYPED FROM MEMORY. The version comes out of the core's
own header (esp_hosted_host_fw_ver.h under ~/.arduino15), the URL is
built the way cores/esp32/esp32-hal-hosted.c builds it, and the file is
refused unless its SHA-256 matches the one recorded below for that
version, so a changed upstream file cannot reach the C6 unnoticed. A
version with no recorded digest is downloaded and its digest printed,
and the script stops: record it here on purpose, then run again.

The image and the generated C file are gitignored (*.bin, c6_image.c):
1.2 MB of Espressif's binary does not belong in this repository.
"""
import argparse
import glob
import hashlib
import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "..", "firmware", "p4-c6-update")
TARGET = "esp32c6"
URL = "https://espressif.github.io/arduino-esp32/hosted/{target}-v{M}.{m}.{p}.bin"

# Recorded by hand after reading the file once (2026-10-12): the digest
# of what espressif.github.io served for 2.12.11 that day.
KNOWN_SHA256 = {
    "2.12.11": "5b05e1530e122881ffeeea3ce2e930963cef6fcc79f930cf0994bf9cb9d709cb",
}


def host_version():
    """The esp-hosted version compiled into the installed P4 core."""
    pats = glob.glob(os.path.expanduser("~/.arduino15/packages/esp32/tools/esp32p4-libs/*/include/espressif__esp_hosted/host/esp_hosted_host_fw_ver.h"))
    if not pats:
        sys.exit("no installed esp32p4 core libraries found under ~/.arduino15 (arduino-cli core install esp32:esp32)")
    path = sorted(pats)[-1]
    text = open(path).read()
    v = {}
    for part in ("MAJOR_1", "MINOR_1", "PATCH_1"):
        m = re.search(r"#define ESP_HOSTED_VERSION_%s (\d+)" % part, text)
        if not m:
            sys.exit(f"{path}: no ESP_HOSTED_VERSION_{part}")
        v[part] = int(m.group(1))
    return v["MAJOR_1"], v["MINOR_1"], v["PATCH_1"], path


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="print the version, URL and digest; fetch nothing")
    args = ap.parse_args()

    M, m, p, hdr = host_version()
    ver = f"{M}.{m}.{p}"
    url = URL.format(target=TARGET, M=M, m=m, p=p)
    name = url.rsplit("/", 1)[1]
    want = KNOWN_SHA256.get(ver)
    print(f"host esp-hosted {ver} (from {hdr})")
    print(f"image {url}")
    print(f"recorded sha256 {want or 'NONE: not recorded for this version'}")
    if args.check:
        return 0

    dst = os.path.join(OUT_DIR, name)
    if not os.path.exists(dst):
        print("fetching...")
        with urllib.request.urlopen(url, timeout=60) as r, open(dst + ".part", "wb") as f:
            f.write(r.read())
        os.replace(dst + ".part", dst)
    data = open(dst, "rb").read()
    got = hashlib.sha256(data).hexdigest()
    print(f"{name}: {len(data)} bytes, sha256 {got}")
    if want is None:
        print(f"REFUSED: no digest recorded for {ver}. Read the file, then add\n    \"{ver}\": \"{got}\",\nto KNOWN_SHA256 and run again.")
        return 1
    if got != want:
        print(f"REFUSED: the digest does not match the recorded one for {ver}. The file changed upstream; read it before recording the new digest.")
        return 1
    if data[0] != 0xE9:
        print("REFUSED: not an ESP app image (no 0xE9 magic)")
        return 1
    chip = int.from_bytes(data[12:14], "little")
    if chip != 13:
        print(f"REFUSED: the image header says chip id {chip}; the ESP32-C6 is 13")
        return 1

    out = os.path.join(OUT_DIR, "c6_image.c")
    with open(out, "w") as f:
        f.write("// GENERATED by tools/fetch-c6-image.py: do not edit, do not commit.\n")
        f.write(f"// {name}, {len(data)} bytes, sha256 {got}\n")
        f.write("#include <stdint.h>\n")
        f.write(f'const char c6_image_name[] = "{name}";\n')
        f.write(f'const char c6_image_sha256[] = "{got}";\n')
        f.write(f"const uint32_t c6_image_len = {len(data)}u;\n")
        f.write("const uint8_t c6_image[] = {\n")
        for i in range(0, len(data), 32):
            f.write("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 32]) + ",\n")
        f.write("};\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
